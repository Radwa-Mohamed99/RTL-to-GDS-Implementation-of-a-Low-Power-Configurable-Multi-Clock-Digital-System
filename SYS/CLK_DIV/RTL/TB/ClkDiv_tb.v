`timescale 1ns/1ps

module ClkDiv_tb;

    //========================================================
    // Parameters
    //========================================================
    parameter DIV_RATIO_WIDTH = 8;

    // UART Clock = 3.6864 MHz
    // Period = 1 / 3.6864 MHz = 271.267 ns
    parameter UART_CLK_PERIOD = 271.267;

    //========================================================
    // DUT Signals
    //========================================================
    reg                         I_ref_clk;
    reg                         I_rst;
    reg                         I_clk_en;
    reg  [DIV_RATIO_WIDTH-1:0]  I_div_ratio;

    wire                        O_div_clk;


    //========================================================
    // DUT
    //========================================================
    ClkDiv #(
        .DIV_RATIO_WIDTH(DIV_RATIO_WIDTH)
    )
    DUT (
        .I_ref_clk   (I_ref_clk),
        .I_rst       (I_rst),
        .I_clk_en    (I_clk_en),
        .I_div_ratio (I_div_ratio),
        .O_div_clk   (O_div_clk)
    );


    //========================================================
    // UART Clock Generation
    // 3.6864 MHz
    //========================================================
    initial
    begin
        I_ref_clk = 1'b0;

        forever
            #(UART_CLK_PERIOD/2) I_ref_clk = ~I_ref_clk;
    end


    //========================================================
    // Test Sequence
    //========================================================
    initial
    begin

        // Initialize
        I_rst       = 1'b0;
        I_clk_en    = 1'b0;
        I_div_ratio = 8'd0;

        // Hold reset
        #1000;

        // Release reset
        I_rst = 1'b1;

        //====================================================
        // Test Ratio = 1
        // Expected:
        // O_div_clk = I_ref_clk
        //====================================================
        I_clk_en    = 1'b1;
        I_div_ratio = 8'd1;

        #5000;


        //====================================================
        // Test Ratio = 2
        //====================================================
        I_div_ratio = 8'd2;

        #5000;


        //====================================================
        // Test Ratio = 4
        //====================================================
        I_div_ratio = 8'd4;

        #8000;


        //====================================================
        // Test Ratio = 8
        //====================================================
        I_div_ratio = 8'd8;

        #12000;


        //====================================================
        // Test Ratio = 32
        //====================================================
        I_div_ratio = 8'd32;

        #30000;


        //====================================================
        // Disable Divider
        //====================================================
        I_clk_en = 1'b0;

        #5000;


        //====================================================
        // Finish Simulation
        //====================================================
        $stop;

    end


    //========================================================
    // Display
    //========================================================
    initial
    begin
        $monitor(
            "TIME=%0t | RESET=%b | CLK_EN=%b | DIV_RATIO=%0d | REF_CLK=%b | DIV_CLK=%b",
            $time,
            I_rst,
            I_clk_en,
            I_div_ratio,
            I_ref_clk,
            O_div_clk
        );
    end

endmodule